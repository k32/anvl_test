-module(anvl_test_cluster).
-moduledoc """
Fixture that creates a familiar cluster on the test node.

Test cases that need a cluster of their own,
e.g. for testing distributed functionality,
add this fixture to their fixture list
and call @erlfn{ref,erlref,anvl_test_cluster,get_cluster,0} to learn the ID of the cluster:

@verbatim
-test(foo).
foo(fixtures, #{instance := default}) ->
  [{anvl_test_cluster, #{}}];
foo(run, #{instance := default}) ->
  Cluster = anvl_test_cluster:get_cluster(),
  {ok, Site} = familiar:create_site(Cluster, site1),
  {ok, _Node} = familiar:start_site(Site).
@end verbatim

The cluster is managed by the temporary node running the test case,
so it can be managed with the regular @code{familiar} API
called from the test case.

@code{net} and @code{subnet} of the cluster
are set by the fixture from the @code{familiar} field of the fixture state,
which holds the network settings allocated for the test case,
and cannot be overridden:
the clusters of the test cases running in parallel never collide this way.
The rest of the cluster configuration
(e.g. @code{fixtures} or @code{peer})
is taken from the fixture configuration.
The auto shutdown of the cluster is always disabled:
the cluster is created by a short-lived RPC process,
and it would be destroyed as soon as the fixture callback completes otherwise.

The cluster is destroyed when the node of the test case is stopped.
""".

-behavior(familiar_fixture).

%% API:
-export([get_cluster/0]).

%% behavior callbacks:
-export([init_per_node/4, cleanup_per_node/5]).

-export_type([conf/0]).

%% Cluster start and stop involve starting applications and peer nodes,
%% so they can take a while:
-define(TIMEOUT, 30_000).

%%================================================================================
%% Type declarations
%%================================================================================

-doc """
Configuration of the cluster, passed to @code{familiar:start_link_cluster/1}.

The @code{net} and @code{subnet} values are set by the fixture
and cannot be overridden.
When @code{id} is not set, it is generated by the fixture.
""".
-type conf() :: familiar:cluster_conf().

%%================================================================================
%% API functions
%%================================================================================

-doc """
Return the ID of the cluster created by the fixture.

The function must be called on the node where the fixture is installed:
it reads the fixture state of this node.
""".
-spec get_cluster() -> familiar:cluster_id().
get_cluster() ->
  #{test_cluster := Cluster} = familiar:fixture_state(),
  Cluster.

%%================================================================================
%% Behavior callbacks
%%================================================================================

-doc false.
init_per_node(Site, _Node, Conf, State = #{familiar := #{net := Net, subnet := Subnet}}) ->
  ClusterId = cluster_id(Conf),
  ClusterConf =
    maps:merge(
      Conf,
      #{ id     => ClusterId
       , net    => {127, Net, 0, 0}
       , subnet => Subnet
       %% The cluster is created by a short-lived RPC process,
       %% and would be destroyed together with it
       %% if the auto shutdown was enabled:
       , auto_shutdown => false
       }),
  case familiar:call(
         Site,
         familiar, start_link_cluster, [ClusterConf],
         ?TIMEOUT) of
    ok ->
      {ok, State#{test_cluster => ClusterId}};
    {error, _} = Error ->
      Error
  end.

-doc false.
cleanup_per_node(Site, _Node, _Conf, #{test_cluster := ClusterId}, _IsKill) ->
  %% The test case may have stopped the cluster itself,
  %% so ignore the return value:
  _ = familiar:call(
        Site,
        familiar, stop_cluster, [ClusterId, true],
        ?TIMEOUT),
  ok.

%%================================================================================
%% Internal functions
%%================================================================================

-spec cluster_id(conf()) -> familiar:cluster_id().
cluster_id(#{id := Id}) ->
  Id;
cluster_id(_) ->
  list_to_binary(peer:random_name(atom_to_list(?MODULE))).
